// npm run sample — regenerates data/sample/, a UI FIXTURE for the dashboard (Stream D) so the web can be
// developed before / without a deployment. It is produced by an offline mock run (in-memory chain, no LLM,
// mock-<n> tx hashes) and is clearly labelled as SAMPLE. It is never the demo of record: the real data
// comes from `npm run demo` on testnet (exported to web/public/offchain).
import fs from "node:fs";
import path from "node:path";
import { createMockMarket, openStore, readChainState, repoRoot } from "@hivefund/shared/node";
import { runMarket } from "./run.ts";

const NOTICE =
  "SAMPLE DATA — generated by an offline mock run (npm run sample). Not on-chain: tx hashes are mock-<n>, " +
  "rubric mode is 'fallback' (no LLM). Real data comes from `npm run demo` on NEAR testnet.";

async function main() {
  const dir = path.join(repoRoot(), "data", "sample");
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  // fixed clock so timestamps are stable across regenerations
  const market = await createMockMarket({ store: openStore(dir), nowMs: Date.UTC(2026, 10, 12, 12, 0, 0), logSink: () => {} });
  const run = await runMarket(market, { maxSteps: 8, log: () => {} });
  const state = await readChainState(market.coordinator.hub, market.token, "mock");
  market.store.writeJson("chain-state.json", { sample: true, notice: NOTICE, ...state, captured_at: new Date(market.now()).toISOString() });
  fs.writeFileSync(path.join(dir, "SAMPLE.md"), `# data/sample\n\n${NOTICE}\n\nFormat: see docs/notes/stream-b.md.\n`);
  fs.writeFileSync(path.join(dir, ".gitkeep"), "");
  console.log(`wrote ${dir}: ${run.finalBounties.map((b) => `#${b.id} ${b.status}`).join(", ")}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
